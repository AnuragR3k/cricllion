import fs from 'node:fs'
import path from 'node:path'
import postgres from 'postgres'

export type Row = Record<string, unknown>

export interface Store {
  readonly kind: 'sqlite' | 'postgres'
  query<T extends Row = Row>(text: string, ...params: unknown[]): Promise<T[]>
  one<T extends Row = Row>(text: string, ...params: unknown[]): Promise<T | undefined>
  run(text: string, ...params: unknown[]): Promise<void>
  exec(text: string): Promise<void>
  transaction<T>(fn: (store: Store) => Promise<T>): Promise<T>
  insertId(text: string, ...params: unknown[]): Promise<number>
  /** Insert many rows from a single-row INSERT statement; returns ids when asked. */
  insertMany(text: string, rows: unknown[][], returningId?: boolean): Promise<number[]>
}

/** SQLite DDL with one Postgres-compatible difference isolated. */
const SCHEMA = `
  CREATE TABLE IF NOT EXISTS meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS prompts (
    id TEXT PRIMARY KEY,
    text TEXT NOT NULL,
    category TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS answers (
    id __ID__ PRIMARY KEY,
    prompt_id TEXT NOT NULL,
    answer TEXT NOT NULL,
    tier TEXT NOT NULL,
    quip TEXT
  );
  CREATE INDEX IF NOT EXISTS idx_answers_prompt ON answers(prompt_id);
  CREATE TABLE IF NOT EXISTS answer_keys (
    prompt_id TEXT NOT NULL,
    key TEXT NOT NULL,
    answer_id INTEGER NOT NULL,
    PRIMARY KEY (prompt_id, key)
  );
  CREATE TABLE IF NOT EXISTS run_prompts (
    run_id TEXT NOT NULL,
    slot INTEGER NOT NULL,
    prompt_id TEXT NOT NULL,
    text TEXT NOT NULL,
    PRIMARY KEY (run_id, slot)
  );
  CREATE INDEX IF NOT EXISTS idx_run_prompts_run ON run_prompts(run_id);
  CREATE TABLE IF NOT EXISTS runs (
    run_id TEXT PRIMARY KEY,
    date TEXT NOT NULL,
    player_id TEXT NOT NULL,
    day_number INTEGER NOT NULL,
    started_at __BIGINT__ NOT NULL,
    completed_at __BIGINT__,
    score INTEGER NOT NULL DEFAULT 0
  );
  CREATE INDEX IF NOT EXISTS idx_runs_player_date ON runs(player_id, date);
  CREATE TABLE IF NOT EXISTS submissions (
    receipt TEXT PRIMARY KEY,
    run_id TEXT NOT NULL,
    date TEXT NOT NULL,
    prompt_id TEXT NOT NULL,
    slot INTEGER NOT NULL,
    raw_answer TEXT NOT NULL,
    answer TEXT,
    tier TEXT NOT NULL,
    score INTEGER NOT NULL,
    quip TEXT,
    match_type TEXT,
    created_at __BIGINT__ NOT NULL,
    UNIQUE (run_id, slot)
  );
  CREATE INDEX IF NOT EXISTS idx_submissions_run ON submissions(run_id);
  CREATE TABLE IF NOT EXISTS popularity (
    date TEXT NOT NULL,
    prompt_id TEXT NOT NULL,
    answer_id INTEGER NOT NULL,
    count INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (date, prompt_id, answer_id)
  );
`

export function schemaFor(kind: Store['kind']): string {
  const bigInt = kind === 'postgres' ? 'BIGINT' : 'INTEGER'
  const schema = SCHEMA.replaceAll('__BIGINT__', bigInt)
  return kind === 'postgres'
    ? schema.replace('__ID__', 'BIGINT GENERATED BY DEFAULT AS IDENTITY')
    : schema
        .replace('__ID__', 'INTEGER PRIMARY KEY AUTOINCREMENT')
        .replace('id INTEGER PRIMARY KEY AUTOINCREMENT PRIMARY KEY', 'id INTEGER PRIMARY KEY AUTOINCREMENT')
}

/** Translate SQLite `?` placeholders and statement forms to Postgres. */
function pgText(text: string): string {
  let index = 0
  return text
    .replace(/INSERT OR IGNORE/gi, 'INSERT')
    .replace(/\?/g, () => `$${++index}`)
}

/** The subset of a postgres.js client used here, shared by pools and transactions. */
interface PgClient {
  unsafe<T extends unknown[] = Row[]>(
    text: string,
    params?: unknown[],
  ): Promise<T>
  begin<T>(fn: (tx: PgClient) => T | Promise<T>): Promise<T>
}

function asClient(sql: unknown): PgClient {
  return sql as PgClient
}

class PgStore implements Store {
  readonly kind = 'postgres' as const

  constructor(private sql: PgClient) {}

  async query<T extends Row = Row>(text: string, ...params: unknown[]): Promise<T[]> {
    return (await this.sql.unsafe<T[]>(pgText(text), params)) as T[]
  }

  async one<T extends Row = Row>(text: string, ...params: unknown[]): Promise<T | undefined> {
    return (await this.query<T>(text, ...params))[0]
  }

  async run(text: string, ...params: unknown[]): Promise<void> {
    await this.sql.unsafe(pgText(text), params)
  }

  async exec(text: string): Promise<void> {
    for (const statement of text.split(';')) {
      const trimmed = statement.trim()
      if (!trimmed || /^PRAGMA/i.test(trimmed)) continue
      await this.sql.unsafe(pgText(trimmed) + ';')
    }
  }

  async transaction<T>(fn: (store: Store) => Promise<T>): Promise<T> {
    return this.sql.begin((tx) => fn(new PgStore(asClient(tx))))
  }

  async insertId(text: string, ...params: unknown[]): Promise<number> {
    const rows = await this.query<{ id: string | number }>(`${text} RETURNING id`, ...params)
    return Number(rows[0]?.id)
  }

  async insertMany(text: string, rows: unknown[][], returningId = false): Promise<number[]> {
    if (!rows.length) return []
    const at = text.toUpperCase().indexOf('VALUES')
    if (at < 0) throw new Error('insertMany needs a VALUES clause')
    const head = text.slice(0, at).trimEnd()
    const tuple = text.slice(at + 'VALUES'.length).trim()
    const values = rows.map(() => tuple).join(', ')
    const params = rows.flat()
    const query = `${head} VALUES ${values}${returningId ? ' RETURNING id' : ''}`
    const result = await this.sql.unsafe<Row[]>(pgText(query), params)
    return returningId ? result.map((row) => Number(row.id)) : []
  }
}

class SqliteStore implements Store {
  readonly kind = 'sqlite' as const

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  constructor(private db: any) {}

  async query<T extends Row = Row>(text: string, ...params: unknown[]): Promise<T[]> {
    return this.db.prepare(text).all(...params) as T[]
  }

  async one<T extends Row = Row>(text: string, ...params: unknown[]): Promise<T | undefined> {
    return this.db.prepare(text).get(...params) as T | undefined
  }

  async run(text: string, ...params: unknown[]): Promise<void> {
    this.db.prepare(text).run(...params)
  }

  async exec(text: string): Promise<void> {
    this.db.exec(text)
  }

  async transaction<T>(fn: (store: Store) => Promise<T>): Promise<T> {
    this.db.exec('BEGIN')
    try {
      const value = await fn(this)
      this.db.exec('COMMIT')
      return value
    } catch (error) {
      this.db.exec('ROLLBACK')
      throw error
    }
  }

  async insertId(text: string, ...params: unknown[]): Promise<number> {
    const result = this.db.prepare(text).run(...params)
    return Number(result.lastInsertRowid)
  }

  async insertMany(text: string, rows: unknown[][], returningId = false): Promise<number[]> {
    if (!rows.length) return []
    const ids: number[] = []
    const stmt = this.db.prepare(text)
    for (const row of rows) {
      const result = stmt.run(...row)
      if (returningId) ids.push(Number(result.lastInsertRowid))
    }
    return ids
  }
}

let cached: Promise<Store> | null = null

export function createStore(): Promise<Store> {
  if (cached) return cached
  cached = (async () => {
    if (process.env.DATABASE_URL) {
      const url = new URL(process.env.DATABASE_URL)
      url.searchParams.delete('sslmode')
      const sql = postgres(url.toString(), {
        max: 1,
        idle_timeout: 20,
        connect_timeout: 10,
        ssl: 'require',
      })
      const store = new PgStore(asClient(sql))
      await store.exec(schemaFor('postgres'))
      return store
    }

    const { DatabaseSync } = await import('node:sqlite')
    const dir = path.join(process.cwd(), '.data')
    fs.mkdirSync(dir, { recursive: true })
    const db = new DatabaseSync(path.join(dir, 'cricllion.db'))
    db.exec('PRAGMA journal_mode = WAL;')
    db.exec('PRAGMA foreign_keys = ON;')
    const store = new SqliteStore(db)
    await store.exec(schemaFor('sqlite'))
    return store
  })()
  return cached
}
